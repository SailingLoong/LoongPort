//! 站点实测数据共建：把本地路由模式的用量事实聚成小时桶，回传公共快照。
//!
//! 与 `relay::stats`（休眠的匿名统计，只报「用了哪几家站」）是**两个模块**：
//! 那个答维护者的优先级问题、默认开；这个是用户功能 —— 用对等条款换数据
//! （参与上传才解锁广场实测数据），默认关、首次触达时征求同意。
//!
//! ## 上传什么、不传什么（这条边界是硬的）
//!
//! | 上传（站点 × 小时聚合） | 不上传 |
//! |---|---|
//! | 站点 host（归一后，与 aff/统计同一套归一） | 提示词、请求体、模型名以外的会话内容 |
//! | 请求数、失败数 | 账号、邮箱、余额、登录标识 |
//! | TTFT 直方图（固定分桶计数，见 [`bins`]） | 密钥（sk / token 任何一种） |
//! | token 计数（输入/输出/缓存读写） | 档位名、分组名、切换记录 |
//! | 桶内总花费（微美元） | 用户可识别的任何标识 |
//! | 一个**每日轮换**的随机 source id | 持久安装标识（与 `stats_install_id` 永不交叉） |
//!
//! ## 为什么 source id 每日轮换而不是持久
//!
//! 服务端拿它做两件事：同日重传去重（幂等键的一部分）、k-匿名的「独立来源」计数。
//! 这两件都不需要跨日关联 —— 轮换后服务端无法把同一安装的周一与周二串起来，
//! 而去重与计源在各自的一天窗口内依然准确。`relay::stats` 的评审结论是
//! 「持久 id + 诚实披露」；这里更进一步直接不持久：能少一个关联维度就少一个。
//!
//! ## 失败静默，水位线只在成功后推进
//!
//! 上传是共建用户的后台动作，不是任何人等的结果：失败只记 log，
//! 下个周期（15 分钟）从水位线重算重发 —— 不排队、不补历史。
//! 水位线存在 DB `settings` 表（`crowd_metrics_flushed_through`），
//! 本地零新表零迁移。首次开启只回溯最近 24 小时，不翻旧账。
//!
//! ## 口径
//!
//! - 小时桶只取 `data_source = 'proxy'` 的行：session 回填行的时间戳是**同步时间**，
//!   不是请求时间，混进来会污染小时归属（且它们本来就没有 TTFT）。
//! - `input_tokens` 走 [`crate::services::sql_helpers::fresh_input_sql`] 归一到
//!   fresh 语义，服务端缓存命中率公式才不被 cache-inclusive app 双计。
//! - 服务端聚合与隐私闸（k-匿名 ≥3、极值源裁剪）见 `crowd-metrics/`（Worker）。
//!
//! ## 展示侧（对等条款）
//!
//! `commands::crowd_get_snapshot` 在 `crowd_metrics_enabled` 关闭时直接返回 `None`：
//! 门禁做在数据访问层，前端锁定态不需要自己「忍住不渲染」。


/**
 * 余额偏低的判据。
 *
 * ## 为什么是个独立模块而不是写在 `RelayRow` 里
 *
 * 这个判据有**两个消费者**（余额那段文字要变色、旁边要出一个叹号），
 * 而且它是这个面板的一条领域规则 —— 写在组件里会让「判据」与「怎么画」缠在一起，
 * 测的时候得渲染整行才能测一个比较。
 *
 * ⚠️ **有意不放 `src/config/constants.ts`**：那里是全局 app 常量
 * （官网 URL、托管前缀、provider 类型），而这是 relay 面板自己的业务阈值。
 * 放进去会让一个只有本面板在意的数字变成全仓的公共词汇。
 */

/**
 * 低于这个金额就提醒充值（美元）。
 *
 * ## 为什么写死而不做成设置项（2026-08-04 维护者拍板）
 *
 * 需求原文就是「少于 5 刀」。做成设置项要新增 settings 字段 + 迁移 + UI 输入框，
 * 而现在**没有第二个消费者**要求它可变 —— 那是为假设场景预留。
 * 将来真要可配，改这里一处 + 加个读取即可（判据函数不必动）。
 *
 * ## 单位是**美元**，与 `RelayAccount.balance` 一致
 *
 * sub2api 的 `balance` 就是美元计价（后台文案写的是「每付 1 CNY 得到多少 USD 余额」），
 * 所以这个阈值不需要汇率换算、也不需要币种判断。
 *
 * ⚠️ 官网直连（vendor）行**不适用**这个阈值。2026-08-04 维护者明确要求：
 * 「只对中转站生效，对 deepseek 之类的不生效」。
 *
 * 2026-08-13 两类行的余额契约统一成上游 `UsageResult`（不再是 `number` vs
 * 已格式化字符串），**类型上的隔离没有了，但那条要求仍然成立** —— DeepSeek 的钱包
 * 是 CNY，拿它跟一个美元阈值比仍然是错的。所以判据改由 `RowBalance` 显式守：
 * 它只在**有充值入口**（`onPurchase`，relay 才传）时才算 `low`。
 * 见 `lowBalanceScopeContract.test.ts`。
 */
export const LOW_BALANCE_THRESHOLD_USD = 5;

/**
 * 这个余额算不算偏低（`null` = 还没拉到 / 拉失败 ⇒ 不算）。
 *
 * ## 边界：正好等于阈值**不算低**
 *
 * 需求原文是「少于 5 刀」⇒ 严格小于。5.00 整不提醒。
 *
 * ## 为什么 `null` 不算低
 *
 * `null` 的含义是「不知道」（还没拉到、或中转站关了用户面板），不是「没钱」。
 * 把不知道当成低余额会给每一行都挂上叹号 —— 那个提醒立刻变成噪音。
 */
export function isLowBalance(balance: number | null): boolean {
  if (balance === null) return false;
  return balance < LOW_BALANCE_THRESHOLD_USD;
}
